import { useState } from "react";
import Section from "../components/Section";
import AlertList from "../components/AlertList";

export default function SecurityAlerts({ alerts }) {
  const [filter, setFilter] = useState("All");
  const filtered = filter === "All" ? alerts : alerts.filter(a => a.type === filter);
  return <div className="page">
    <div className="page-intro"><div><h2>Security events</h2><p>Review recent alerts generated by the LAN monitoring layer.</p></div><span className="event-count">{filtered.length} events</span></div>
    <Section title="Event log" subtitle="Filter events by monitoring category">
      <div className="filter-tabs">{["All","Unauthorized","Bandwidth","Network"].map(x=><button key={x} className={filter===x?"selected":""} onClick={()=>setFilter(x)}>{x}</button>)}</div>
      <AlertList alerts={filtered}/>
    </Section>
  </div>;
}
